import { promises as fs } from 'node:fs'
import path from 'node:path'

import { classifyQuery } from '@/lib/agents/query-classifier'

import { CASES } from './classifier-cases'

const BASELINE = path.join(__dirname, 'classifier-baseline.json')

type Result = {
  skipSearch: boolean
  standaloneQuery: string
  needsRecent: boolean
  // Gates whether the turn retrieves AT ALL (researcher.ts resolveTurnMode).
  // Absent from this harness until now, which meant the one classifier field
  // that is live on prod was the one field a parity run could not protect.
  needsSources: boolean
  intent: string
}

async function run(): Promise<Record<string, Result>> {
  const out: Record<string, Result> = {}
  for (const c of CASES) {
    const r = await classifyQuery({ messages: c.messages })
    out[c.name] = {
      skipSearch: r.skipSearch,
      standaloneQuery: r.standaloneQuery,
      needsRecent: r.needsRecent,
      needsSources: r.needsSources,
      intent: r.intent
    }
    console.log(
      `  ${c.name}: skip=${r.skipSearch} recent=${r.needsRecent} sources=${r.needsSources} intent=${r.intent} q="${r.standaloneQuery}"`
    )
  }
  return out
}

async function main() {
  const mode = process.argv[2]
  if (mode === '--capture') {
    const results = await run()
    await fs.writeFile(BASELINE, JSON.stringify(results, null, 2) + '\n')
    console.log(`\nBaseline written: ${BASELINE}`)
    return
  }
  if (mode === '--check') {
    const baseline: Record<string, Result> = JSON.parse(
      await fs.readFile(BASELINE, 'utf8')
    )
    const now = await run()
    let failed = 0
    console.log('\n=== parity vs baseline ===')
    for (const c of CASES) {
      const b = baseline[c.name]
      const n = now[c.name]
      const decisionOk =
        b.skipSearch === n.skipSearch &&
        b.needsRecent === n.needsRecent &&
        b.needsSources === n.needsSources &&
        b.intent === n.intent
      // standaloneQuery is REPORTED, never fatal. It is free text generated by
      // the model, and measured run-to-run against a baseline captured minutes
      // earlier, 1 of 12 cases rewords itself while every decision stays
      // identical. Gating on exact text therefore manufactures roughly one
      // false failure per run, which is worse than not checking: a gate that
      // cries wolf is a gate whose real failures get scrolled past. The
      // DECISIONS are deterministic (12/12 stable) and stay fatal.
      const queryOk = b.skipSearch
        ? true
        : b.standaloneQuery === n.standaloneQuery
      if (decisionOk) {
        console.log(
          queryOk
            ? `  PASS ${c.name}`
            : `  PASS ${c.name}  (query reworded, decisions identical)\n       was: "${b.standaloneQuery}"\n       now: "${n.standaloneQuery}"`
        )
      } else {
        failed++
        console.log(
          `  FAIL ${c.name}: DECISION DRIFT\n    baseline: ${JSON.stringify(b)}\n    now:      ${JSON.stringify(n)}`
        )
      }
    }
    if (failed > 0) {
      console.error(`\n${failed} case(s) drifted — DO NOT SHIP.`)
      process.exit(1)
    }
    console.log('\nAll cases parity-clean.')
    return
  }
  console.error('usage: classifier-eval.ts --capture | --check')
  process.exit(2)
}

main().catch(e => {
  console.error(e)
  process.exit(1)
})
